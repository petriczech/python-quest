import { Level, World } from '../core/level';
import { Command } from '../core/program';

const fwd = (value: number): Command => ({ kind: 'forward', value });
const back = (value: number): Command => ({ kind: 'backward', value });
const left = (angle: number): Command => ({ kind: 'left', angle });
const right = (angle: number): Command => ({ kind: 'right', angle });
const penUp: Command = { kind: 'penUp' };
const penDown: Command = { kind: 'penDown' };
const repeat = (times: number, body: Command[]): Command => ({ kind: 'repeat', times, body });
const fill = (color: string, body: Command[]): Command => ({ kind: 'fill', color, body });

const square = (side: number): Command[] =>
  [fwd(side), left(90), fwd(side), left(90), fwd(side), left(90), fwd(side), left(90)];

